"""experiment-v1: the S08 controlled quant-exploration round trip.

Architecture (docs/research/s08-exploration-loop-design.md): when the
standard quant library does not cover a research need, the Controller spawns
an ISOLATED experiment instance (its own Hermes container, no shared memory
with the research instance). The experiment instance generates code —
untrusted job input — and drives sandboxed computations through platform
tools (submit / status / read), each separately authorized. Artifacts come
back bounded and content-hashed, are recorded append-only by the Controller,
and are cited by the research instance as
``experiment:<id>/artifacts/<path>`` references (kind "code").

Trust model mirrors the research link: the experiment container never
chooses its inputs (the Runner injects the frozen snapshot), never holds a
signing key, and every tool call re-verifies a Controller-signed Ed25519
grant (aud=runner-tools, scopes experiment:submit / experiment:status /
experiment:read — see research_capability.py).

This file is a wire contract: no database or upstream SDK imports.
"""

from __future__ import annotations

import hashlib
import json
import re
import uuid
from pathlib import PurePosixPath
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

from youwei_contracts.sandbox import check_argv_env


class WireModel(BaseModel):
    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)


# Artifact extensions the sandbox may produce (same set as sandbox-v1).
from youwei_contracts.sandbox import ARTIFACT_EXTENSIONS  # noqa: E402

_TERMINAL_FAILURES = ("failed", "cancelled", "timeout")


# --- research instance -> Controller: the ask -------------------------------


class ExperimentRequest(WireModel):
    """The research instance's request for an experiment (its turn output).

    Bounded and declarative: the Controller checks per-case experiment caps
    and shape before spawning anything. No code here — code is generated by
    the experiment instance, never by the research instance.
    """

    contract_version: Literal["experiment-v1"] = "experiment-v1"
    question: str = Field(min_length=1, max_length=2000)
    motivation: str = Field(min_length=1, max_length=2000)
    requested_shape: str = Field(min_length=1, max_length=2000)


# --- experiment instance -> Runner: one sandboxed computation ---------------


class ExperimentComputationRequest(WireModel):
    """One generated-code computation submitted by the experiment instance.

    The frozen snapshot is NOT a field: the Runner injects it from the
    invocation's binding (the caller cannot redirect its own input). Bounds
    mirror sandbox-v1's script semantics.
    """

    contract_version: Literal["experiment-v1"] = "experiment-v1"
    experiment_invocation_id: uuid.UUID
    computation_id: uuid.UUID
    code: str = Field(min_length=1, max_length=1_000_000)
    argv: list[str] = Field(default_factory=list)
    env: dict[str, str] = Field(default_factory=dict)
    expected_extensions: list[str] = Field(min_length=1, max_length=8)
    timeout_seconds: float = Field(ge=1.0, le=3600.0)

    @model_validator(mode="after")
    def validate_request(self):
        check_argv_env(self.argv, self.env)
        if len(set(self.expected_extensions)) != len(self.expected_extensions):
            raise ValueError("duplicate expected extension")
        if any(ext not in ARTIFACT_EXTENSIONS for ext in self.expected_extensions):
            raise ValueError("unknown artifact extension")
        return self


# --- Runner -> experiment instance: bounded status --------------------------


class ArtifactManifest(WireModel):
    """An artifact's identity without its content (status payloads are polled
    repeatedly; content comes back only via artifact_read)."""

    path: str
    extension: str
    size: int = Field(ge=0, le=16 * 1024 * 1024)
    sha256: str

    @model_validator(mode="after")
    def validate_manifest(self):
        path = PurePosixPath(self.path)
        if (not self.path or path.is_absolute() or ".." in path.parts
                or "\\" in self.path or "\0" in self.path
                or path.as_posix() != self.path
                or path.suffix != self.extension
                or self.extension not in ARTIFACT_EXTENSIONS):
            raise ValueError("invalid artifact path")
        if not re.fullmatch(r"[0-9a-f]{64}", self.sha256):
            raise ValueError("artifact sha256 must be a lowercase hex digest")
        return self


class ExperimentComputationStatus(WireModel):
    """Status of one computation. ``partial`` is True exactly when a terminal
    failure still left artifacts on disk (they remain readable and citable
    with the partial caveat)."""

    contract_version: Literal["experiment-v1"] = "experiment-v1"
    experiment_invocation_id: uuid.UUID
    computation_id: uuid.UUID
    status: Literal["running", "succeeded", "failed", "cancelled", "timeout"]
    partial: bool = False
    stdout_excerpt: str = Field(default="", max_length=4000)
    stderr_excerpt: str = Field(default="", max_length=4000)
    artifacts: list[ArtifactManifest] = Field(default_factory=list, max_length=50)
    error: str | None = Field(default=None, max_length=2000)
    duration_seconds: float = Field(ge=0)

    @model_validator(mode="after")
    def validate_partial(self):
        if len({a.path for a in self.artifacts}) != len(self.artifacts):
            raise ValueError("duplicate artifact path")
        if self.status in _TERMINAL_FAILURES:
            if self.partial and not self.artifacts:
                raise ValueError("partial requires artifacts")
        elif self.partial:
            raise ValueError("only terminal failures may be partial")
        return self


# --- experiment instance -> Controller: the experiment's outcome ------------


class ExperimentResultComputation(WireModel):
    """One computation as reported in the experiment result: the code (for
    reproducible attribution), its hash, the terminal status, and the
    artifacts produced. ``running`` is not a valid result entry."""

    computation_id: uuid.UUID
    code: str = Field(min_length=1, max_length=1_000_000)
    code_sha256: str
    status: Literal["succeeded", "failed", "cancelled", "timeout"]
    artifacts: list[ArtifactManifest] = Field(default_factory=list, max_length=50)

    @model_validator(mode="after")
    def validate_computation(self):
        actual = hashlib.sha256(self.code.encode("utf-8")).hexdigest()
        if actual != self.code_sha256:
            raise ValueError("code hash mismatch")
        if len({a.path for a in self.artifacts}) != len(self.artifacts):
            raise ValueError("duplicate artifact path")
        return self


class ExperimentResult(WireModel):
    """The experiment instance's final output: bounded findings, warnings,
    and the computations it ran (code + artifacts, all hash-checked). The
    Controller re-verifies and records this append-only before the research
    instance may cite it."""

    contract_version: Literal["experiment-v1"] = "experiment-v1"
    findings: str = Field(min_length=1, max_length=20000)
    warnings: list[str] = Field(default_factory=list, max_length=32)
    computations: list[ExperimentResultComputation] = Field(
        default_factory=list, max_length=16
    )

    @model_validator(mode="after")
    def validate_result(self):
        if any(len(w) > 500 for w in self.warnings):
            raise ValueError("experiment warning too long")
        if len({c.computation_id for c in self.computations}) != len(self.computations):
            raise ValueError("duplicate computation id")
        return self


# --- citation locator --------------------------------------------------------


def experiment_artifact_locator(experiment_id: uuid.UUID, path: str) -> str:
    """Name an experiment artifact at its recorded path."""
    _validate_artifact_path(path)
    return f"experiment:{experiment_id}/artifacts/{path}"


def parse_experiment_locator(locator: str) -> tuple[uuid.UUID, str]:
    """Parse ``experiment:<uuid>/artifacts/<path>``; raises ValueError on any
    other shape."""
    if not isinstance(locator, str) or not locator.startswith("experiment:"):
        raise ValueError("not an experiment artifact locator")
    rest = locator[len("experiment:"):]
    exp_id_str, sep, path = rest.partition("/artifacts/")
    if not sep or not path:
        raise ValueError("malformed experiment artifact locator")
    try:
        experiment_id = uuid.UUID(exp_id_str)
    except ValueError as exc:
        raise ValueError("invalid experiment id in locator") from exc
    _validate_artifact_path(path)
    return experiment_id, path


def _validate_artifact_path(path: str) -> None:
    p = PurePosixPath(path)
    if (not path or path == "." or path.endswith("/")
            or p.is_absolute() or ".." in p.parts or "\\" in path
            or "\0" in path or p.as_posix() != path):
        raise ValueError("invalid artifact path")


def canonical_json(model: BaseModel) -> str:
    """Canonical JSON for hashing experiment payloads (sorted keys, compact)."""
    return json.dumps(
        model.model_dump(mode="json"), sort_keys=True,
        separators=(",", ":"), ensure_ascii=False,
    )
